      @media print { button { display: none; } body { padding: 16px; } }
    </style>
  </head>
  <body>
    <h1>MVCS Monthly Contribution Report</h1>
    <div class="meta">
      <div><strong>Period:</strong> ${_escapeHtml(period)}</div>
