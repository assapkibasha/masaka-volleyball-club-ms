          <th>Paid</th>
        </tr>
      </thead>
      <tbody>${_buildRows(paidMembers)}</tbody>
    </table>
    <h2>People To Pay</h2>
    <table>
      <thead>
        <tr>
          <th>Name</th>
          <th>Phone</th>
          <th>Email</th>
          <th>Expected</th>
          <th>Paid</th>
