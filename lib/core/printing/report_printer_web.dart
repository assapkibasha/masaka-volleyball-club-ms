      <tbody>${_buildRows(peopleToPay)}</tbody>
    </table>
    <footer>Generated by MVCS, a product of Higura Ventures</footer>
    <script>window.print();</script>
  </body>
</html>
''';

  final uri = Uri.dataFromString(
    htmlContent,
    mimeType: 'text/html',
    encoding: utf8,
  );
  html.window.open(uri.toString(), '_blank');
}
