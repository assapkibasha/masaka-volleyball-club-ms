      .card h3 { font-size: 12px; color: #6b7280; letter-spacing: 0.08em; text-transform: uppercase; }
      .card .value { font-size: 24px; font-weight: 700; margin-top: 8px; }
      .green { color: #15803d; }
      .red { color: #dc2626; }
      .counts { display: flex; gap: 12px; margin-bottom: 24px; }
      table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
